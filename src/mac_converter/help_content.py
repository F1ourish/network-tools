"""Concise offline, contextual help for every desktop tool."""

from dataclasses import dataclass


@dataclass(frozen=True)
class ToolHelp:
    name: str
    purpose: str
    steps: str
    example: str
    limits: str

    def text(self) -> str:
        layout = (
            "\n\nКрупные поля заполняют свободное место. Потяните за полоску у края для изменения "
            "высоты или ширины, за угол - в обе стороны. Двойной щелчок возвращает автоматический "
            "размер. «Развернуть» или Ctrl+Enter открывают поле отдельно; Escape возвращает во вкладку."
            if self.name in ("Маршруты", "ACL", "Свободные IP", "CUCME")
            else ""
        )
        return (
            f"Зачем\n{self.purpose}\n\nКак использовать\n{self.steps}{layout}\n\n"
            f"Пример\n{self.example}\n\nЧто учитывать\n{self.limits}"
        )


